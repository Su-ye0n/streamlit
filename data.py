def pick_questions(n=10, seed=None):
    """분야 8개에서 1문항씩 뽑고, 나머지는 남은 문항에서 무작위로 채운다."""
    rng = random.Random(seed)
    chosen = []
    for cat in CATEGORIES:
        pool = [q for q in QUESTIONS if q["category"] == cat]
        chosen.append(rng.choice(pool))
    rest = [q for q in QUESTIONS if q not in chosen]
    chosen += rng.sample(rest, n - len(chosen))
    # 쉬운 문제부터 나오도록 정렬
    return sorted(chosen, key=lambda q: q["level"])


def get_level(score, max_score):
    pct = score / max_score * 100 if max_score else 0
    return [lv for lv in LEVELS if pct >= lv["min"]][-1]
